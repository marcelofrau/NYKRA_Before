"""Port the reconstructed phase-1 scripts to GameMaker LTS 2026 project scripts.

Usage (from repo root):
    python -P rea/NYKRA_Reconstructed/Tools/generate_project_scripts.py

Reads ReconstructedGML/phase1_core/<name>.gml (pre-2.3 style script bodies) and writes
GameMakerProject/scripts/<name>/<name>.gml + .yy, and registers them in the .yyp.
The logic is kept as reconstructed. Only these edits are applied, all listed in each
generated file header:
  compat  - functions that do not exist in LTS 2026 (array_get_2D, array_length_1d) and
            arrays created from a number (`map = -1; map[..] = ..`), which 2.3+ rejects.
  policy  - map_load never creates a sprite with -1 and stops reading the object list at an
            unknown object, because its payload size is unknown (PHASE3 plan section 1).
"""
import re
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
sys.path.insert(0, str(TOOLS))
from yyp_edit import update_yyp  # noqa: E402

REA = TOOLS.parent
SOURCE = REA / "ReconstructedGML" / "phase1_core"
PROJECT = REA / "GameMakerProject"
SCRIPTS = ["map_load", "clear_objects", "reset_files", "_SET_SCENE", "goto_map"]
# Scripts whose .gml is written by hand: copied from the original repository root (reach_tween,
# set_game_screen) or reconstructed from the decompilation (set_controls, config_get).
HAND_SCRIPTS = ["reach_tween", "set_game_screen", "set_controls", "config_get", "draw_sprite_skew",
                "check_array_cell", "check_array", "check_block", "bb_setmiddle", "ARRAY_COLLIDE",
                "playerhascontrol", "reach", "obj_setpos", "instance_create_one", "sleep", "hrnd",
                "box_inside_bound", "real_string", "ini_language",
                "player_distance", "player_interact", "interact_arrow", "draw_ui_arrow", "draw_rectangle_view",
                "easing", "create_fx", "play_sound", "play_sound_pos", "snd_step_grass", "snd_step_dirt", "snd_step_stone", "snd_step_wood"]

GET_2D = re.compile(r"array_get_2D\((\w+),\s*(\w+),\s*(\w+)\)")
LENGTH_1D = re.compile(r"array_length_1d\(([^()]+)\)")
ARRAY_FROM_NUMBER = [
    ("map = -1;\nmap[mw, mh] = 0;", "map = [];\nmap[mw, mh] = 0;"),
    ("collision_list = 0;\ncollision_list[0] = noone;", "collision_list = [];\ncollision_list[0] = noone;"),
]
POLICY_SPRITE = (
    "        var _aspr = asset_get_index(_aspr_name);\n"
    "        var _sp_inst = layer_sprite_create(_al_id, _ax, _ay, _aspr);\n",
    "        var _aspr = asset_get_index(_aspr_name);\n"
    "        if (_aspr == -1 || asset_get_type(_aspr_name) != asset_sprite) {\n"
    "            // POLICY EDIT (not in the original): never create a sprite with -1.\n"
    "            log_verbose(\"map_load: skipped sprite record '\" + _aspr_name + \"' at (\" + string(_ax) + \",\" + string(_ay) + \")\");\n"
    "            continue;\n"
    "        }\n"
    "        var _sp_inst = layer_sprite_create(_al_id, _ax, _ay, _aspr);\n",
)
POLICY_OBJECT = (
    "    var _oidx = asset_get_index(_oname);\n"
    "    if (_oidx != -1) {\n",
    "    var _oidx = asset_get_index(_oname);\n"
    "    if (_oidx == -1 || asset_get_type(_oname) != asset_object) {\n"
    "        // POLICY EDIT (not in the original): the payload size of an unknown object is unknown,\n"
    "        // so reading on would silently desynchronise the rest of the file.\n"
    "        log_note(\"map_load: unknown object '\" + _oname + \"'; stopping the object list here\");\n"
    "        break;\n"
    "    }\n"
    "    if (_oidx != -1) {\n",
)


def convert(name, text):
    """Return the LTS 2026 project script text for one reconstructed script."""
    text = text.replace("\r\n", "\n")
    lines = text.split("\n")
    head = []
    while lines and lines[0].startswith("///"):
        head.append(lines.pop(0))
    body = "\n".join(lines).strip("\n")
    compat = []
    body, n = GET_2D.subn(r"\1[\2, \3]", body)
    if n:
        compat.append(f"array_get_2D -> a[i, j] ({n}x)")
    body, n = LENGTH_1D.subn(r"array_length(\1)", body)
    if n:
        compat.append(f"array_length_1d -> array_length ({n}x)")
    for old, new in ARRAY_FROM_NUMBER:
        if old in body:
            body = body.replace(old, new)
            compat.append(f"'{old.splitlines()[0]}' -> '{new.splitlines()[0]}'")
    policy = []
    if name == "map_load":
        for label, (old, new) in (("no sprite with -1", POLICY_SPRITE), ("stop at unknown object", POLICY_OBJECT)):
            if body.count(old) != 1:
                raise ValueError(f"map_load: expected exactly one match for policy edit '{label}'")
            body = body.replace(old, new)
            policy.append(label)
    header = list(head)
    header.append(f"/// Generated by Tools/generate_project_scripts.py from ReconstructedGML/phase1_core/{name}.gml. Do not edit by hand.")
    header.append("/// Compat edits: " + ("; ".join(compat) if compat else "none"))
    header.append("/// Policy edits: " + ("; ".join(policy) if policy else "none"))
    return "\n".join(header) + f"\nfunction {name}() {{\n{body}\n}}\n"


def script_yy(name):
    return (
        "{\n"
        '  "$GMScript":"v1",\n'
        f'  "%Name":"{name}",\n'
        '  "isCompatibility":false,\n'
        '  "isDnD":false,\n'
        f'  "name":"{name}",\n'
        '  "parent":{\n'
        '    "name":"Scripts",\n'
        '    "path":"folders/Scripts.yy",\n'
        "  },\n"
        '  "resourceType":"GMScript",\n'
        '  "resourceVersion":"2.0",\n'
        "}\n"
    )


def main():
    for name in SCRIPTS:
        out_dir = PROJECT / "scripts" / name
        out_dir.mkdir(parents=True, exist_ok=True)
        text = convert(name, (SOURCE / f"{name}.gml").read_text(encoding="utf-8"))
        (out_dir / f"{name}.gml").write_text(text, encoding="utf-8", newline="\n")
        (out_dir / f"{name}.yy").write_text(script_yy(name), encoding="utf-8", newline="\n")
        print(f"wrote scripts/{name}")
    for name in HAND_SCRIPTS:  # their .gml is maintained by hand; only the .yy is written here
        yy = PROJECT / "scripts" / name / f"{name}.yy"
        if not yy.exists():
            yy.write_text(script_yy(name), encoding="utf-8", newline="\n")
    resources = [(n, f"scripts/{n}/{n}.yy") for n in SCRIPTS + HAND_SCRIPTS + ["provisional_stubs"]]
    update_yyp(PROJECT / "NYKRA_VerticalSlice.yyp", add_resources=resources,
               add_folders=[("Scripts", "folders/Scripts.yy")])
    print("updated .yyp")


if __name__ == "__main__":
    main()
