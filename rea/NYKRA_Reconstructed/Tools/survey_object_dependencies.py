"""Read-only dependency survey of objects that already have original GML (plan section 3, milestone 3.3).

Usage (from repo root):
    python -P rea/NYKRA_Reconstructed/Tools/survey_object_dependencies.py OBJECT [OBJECT ...] [--out report.md]

For each object folder at the repository root (oPlayer, oEo, oControl, ...) it scans the events'
GML for names of game scripts, objects, sprites and sounds, and reports for every script its status
(reconstructed / decompiled / original GML / todo) and the lifted-size hint when it was decompiled.
Also lists the events the YYC build has for the object (objects-metadata.json) and which of them have
no original GML at the root (so they must be lifted from the executable).
"""
import json
import re
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
sys.path.insert(0, str(TOOLS))
import survey_dependencies as sd  # noqa: E402


def main(argv):
    args = argv[1:]
    out_path = None
    if "--out" in args:
        i = args.index("--out")
        out_path = Path(args[i + 1])
        del args[i:i + 2]
    obj_by_name, sprites, functions = sd.load_context()
    order = sd.load_asset_order()
    kind_of = {n: k for k, v in order.items() for n in v}
    lines = ["# Dependency survey by object (generated by Tools/survey_object_dependencies.py)\n"]
    for obj in args:
        folder = sd.REPO / obj
        files = sorted(folder.glob("*.gml")) if folder.is_dir() else []
        ids = set()
        for f in files:
            ids |= sd.identifiers(f.read_text(encoding="utf-8", errors="replace"))
        found = {}
        for i in ids:
            if i in kind_of:
                found.setdefault(kind_of[i], set()).add(i)
        declared, have = [], []
        meta = obj_by_name.get(obj)
        if meta:
            declared, have = sd.object_events(meta, functions)
        original_events = {f.stem for f in files}
        lines.append(f"## {obj}\n")
        lines.append(f"- YYC events: {len(declared)}; events with original GML at the root: {len(original_events)} ({', '.join(sorted(original_events)) or 'none'})")
        yyc_names = {d.split(f'gml_Object_{obj}_', 1)[1] for d in declared}
        missing = sorted(yyc_names - original_events)
        lines.append(f"- YYC events without original GML (need lifting): {', '.join(missing) or 'none'}")
        lines.append("- referenced: " + ", ".join(f"{len(found.get(k, ()))} {k}" for k in ("objects", "sprites", "sounds", "scripts", "shaders", "fonts") if found.get(k)))
        lines.append("")
        lines.append("| script | status |")
        lines.append("|---|---|")
        counts = {}
        for s in sorted(found.get("scripts", ())):
            status = sd.script_status(s, functions) or "not a game script"
            counts[status.split(" (")[0]] = counts.get(status.split(" (")[0], 0) + 1
            lines.append(f"| `{s}` | {status} |")
        lines.append(f"\nStatus count: {counts}\n")
        for kind in ("objects",):
            names = sorted(found.get(kind, ()))
            lines.append(f"Objects referenced: {', '.join(names)}\n")
    text = "\n".join(lines) + "\n"
    if out_path:
        out_path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {out_path}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
